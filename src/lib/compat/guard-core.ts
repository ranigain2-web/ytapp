/**
 * Should the background guard auto-resume a paused player?
 * Attribution rules: never fight the user (a pause within a short window of
 * a user interaction — or one the app itself executed on the user's behalf —
 * is intentional); never fight an ad (resuming into ad playback corrupts the
 * session); three attempts max so a genuinely stuck player is left alone.
 */
export function shouldAutoResume(state: {
  isUserPause: boolean;
  attempts: number;
  ended: boolean;
  adPlaying: boolean;
}): boolean {
  return !state.isUserPause && state.attempts < 3 && !state.ended && !state.adPlaying;
}

/**
 * Is this node YouTube's "Video paused. Continue watching?" dialog?
 * Signature (measured behavior): the text matches "continue watching" and it
 * offers exactly ONE button — a two-button dialog is a different question
 * and must never be auto-clicked.
 */
export function isContinueWatchingDialog(info: { text: string; buttonCount: number }): boolean {
  return /continue watching/i.test(info.text) && info.buttonCount === 1;
}

/** InnerTube payload keys that only ever carry ads. */
export const AD_PAYLOAD_KEYS = [
  "adPlacements",
  "adSlots",
  "adSlotsHttpServer",
  "playerAds",
  "adBreakHeartbeatParams",
];

/**
 * Deep-clone an InnerTube JSON payload with every ad-carrying key removed.
 * Non-objects pass through untouched; cycles are cut (a seen map guards the
 * walk). stats.stripped counts removals so callers can report how much ad
 * surface was destroyed.
 */
export function stripAdPayload(value: unknown, stats?: { stripped: number }): unknown {
  if (!value || typeof value !== "object") return value;
  // Inlined on purpose: this function's source is embedded standalone into
  // the compat injection, where module scope does not exist.
  var keys = ["adPlacements", "adSlots", "adSlotsHttpServer", "playerAds", "adBreakHeartbeatParams"];
  var seen = new Set<object>();
  function walk(node: unknown): unknown {
    if (!node || typeof node !== "object") return node;
    if (seen.has(node as object)) return undefined; // cycle: cut, never loop
    seen.add(node as object);
    if (Array.isArray(node)) {
      var arr: unknown[] = [];
      for (var i = 0; i < node.length; i++) {
        var item = walk(node[i]);
        if (item !== undefined) arr.push(item);
      }
      return arr;
    }
    var out: Record<string, unknown> = {};
    for (var k of Object.keys(node as Record<string, unknown>)) {
      if (keys.indexOf(k) !== -1) {
        if (stats) stats.stripped++;
        continue;
      }
      var v = walk((node as Record<string, unknown>)[k]);
      if (v !== undefined) out[k] = v;
    }
    return out;
  }
  return walk(value);
}

/**
 * Render a "Cookie: a=1; b=2" header as a Netscape cookies.txt file (the
 * format yt-dlp and curl consume). Expiry is set far-future: these are
 * session cookies being exported for the user's OWN server, and a past
 * expiry would make yt-dlp drop them.
 */
export function toNetscapeCookieFile(cookieHeader: string, pageUrl: string): string {
  var host = "www.youtube.com";
  try {
    host = new URL(pageUrl).host;
  } catch (e) { /* keep default */ }
  var domain = host.replace(/^(www|m)\./, "");
  var lines = ["# Netscape HTTP Cookie File", "# generated by ytapp Compat Mode"];
  var pairs = String(cookieHeader || "").split(";").map(function (p) { return p.trim(); }).filter(Boolean);
  for (var i = 0; i < pairs.length; i++) {
    var eq = pairs[i].indexOf("=");
    if (eq <= 0) continue;
    var name = pairs[i].slice(0, eq);
    var val = pairs[i].slice(eq + 1);
    if (!name || !val) continue;
    // domain  includeSubdomains  path  secure  expiry  name  value
    lines.push("." + domain + "\tTRUE\t/\t" + (name === "VISITOR_INFO1_LIVE" ? "FALSE" : "TRUE") + "\t2147483647\t" + name + "\t" + val);
  }
  return lines.join("\n") + "\n";
}
